class BuildError(Exception):
    pass


def title_of(pages, name, lang):
    for page, title in pages:
        if page == name:
            return title if isinstance(title, str) else title[lang]

    raise BuildError(f'no page {name}')


class Site:
    def __init__(self, out: Path, source_base: str, site: bool = False, dest: Path = None):
        self.out = out
        self.source_base = source_base
        self.site = site
        # where the pages end up (docs/, or --out's): relative source links start there
        self.dest = (dest or DOCS).resolve()
        self.headers = apiref.parse_all(ROOT / 'include' / 'hdrgrading')
        self.linker = apiref.Linker(self.headers)
        self.tr = apiref.Translations(self.headers)
        self.diagrams = {f().name: f() for f in diagrams.ALL}
        self.warnings: list = []
        self.used_figures: set = set()

    # --- paths ---

    @staticmethod
    def page_path(part: str, lang: str, name: str) -> str:
        """The page's path under docs/."""
        return (f'{lang}/{name}.html' if part == 'user' else f'dev/{lang}/{name}.html')

    @staticmethod
    def rel(from_path: str, to_path: str) -> str:
        """A relative URL from one file under docs/ to another."""
        up = from_path.count('/')

        return '../' * up + to_path

    def source_href(self, from_path: str, path: str) -> str:
        if self.source_base:
            base = self.source_base.rstrip('/')
            # GitHub shows a directory under tree/, a file under blob/
            if (ROOT / path.split('#')[0]).is_dir():
                base = base.replace('/blob/', '/tree/', 1)
            return base + '/' + path

        return os.path.relpath(ROOT / path, (self.dest / from_path).parent).replace(os.sep, '/')

    # --- placeholders ---

    def expand(self, text: str, part: str, lang: str, here: str) -> str:
        def repl(m):
            kind, arg = m.group(1), m.group(2)
            target, _, label = arg.partition('|')
            target = target.strip()
            if kind == 'fig':
                return self.figure(target, lang, here)
            if kind == 'src':
                path = target.split('#')[0]
                # dev/ is the developers' own (ignored): never linked from the docs
                if path == 'dev' or path.startswith('dev/'):
                    raise BuildError(f'{here}: {{{{src:{target}}}}} is under dev/ (not published)')
                if not (ROOT / path).exists():
                    raise BuildError(f'{here}: {{{{src:{target}}}}} does not exist')
                text = label or target
                return (f'<a class="src" href="{html.escape(self.source_href(here, target))}">'
                        f'<code>{html.escape(text)}</code></a>')
            if kind == 'api':
                ref = self.linker.href(target, '')
                if ref is None:
                    raise BuildError(f'{here}: {{{{api:{target}}}}} is not in the headers')
                page, _, anchor = ref.partition('#')
                href = self.rel(here, f'dev/{lang}/api/{page}') + '#' + anchor
                text = label or target
                return f'<a class="api" href="{html.escape(href)}"><code>{html.escape(text)}</code></a>'
            if kind in ('page', 'man', 'dev'):
                to_part = part if kind == 'page' else ('user' if kind == 'man' else 'dev')
                pages = USER_PAGES if to_part == 'user' else DEV_PAGES
                name, _, anchor = target.partition('#')
                text = label or title_of(pages, name, lang)
                href = self.rel(here, self.page_path(to_part, lang, name))
                return f'<a href="{href}{"#" + anchor if anchor else ""}">{text}</a>'
            raise BuildError(f'{here}: unknown placeholder {m.group(0)}')

        return re.sub(r'\{\{(fig|src|api|page|man|dev):([^}]*)\}\}', repl, text)

    def figure(self, name: str, lang: str, here: str) -> str:
        if name not in self.diagrams:
            raise BuildError(f'{here}: no diagram {name}')
        d = self.diagrams[name]
        self.used_figures.add(name)
        src = self.rel(here, f'{lang}/img/{name}.svg')
        title = html.escape(pick(d.title, lang))

        # inline, so that the page's theme switch reaches it (the .svg file follows the system's)
        svg = d.render(lang).strip()

        return (f'<figure class="diagram">{svg}<figcaption>{title} · '
                f'<a href="{src}">{UI[lang]["figure_open"]} (SVG)</a></figcaption></figure>\n\n')

    # --- pages ---

    def nav(self, part: str, lang: str, here: str, current: str) -> str:
        pages = USER_PAGES if part == 'user' else DEV_PAGES
        items = []
        for name, title in pages:
            t = title if isinstance(title, str) else title[lang]
            cls = ' class="current" aria-current="page"' if name == current else ''
            indent = ' class="sub"' if name.startswith('api/') and name != 'api/index' else ''
            href = self.rel(here, self.page_path(part, lang, name))
            label = f'<code>{t}</code>' if isinstance(title, str) else t
            items.append(f'<li{indent}><a href="{href}"{cls}>{label}</a></li>')

        return f'<nav class="side" aria-label="{UI[lang]["pages"]}"><ul>{"".join(items)}</ul></nav>'

    def page(self, part: str, lang: str, name: str, body: str, title: str, src: str,
             wide: bool = False, aside: str = '') -> str:
        here = self.page_path(part, lang, name)
        ui = UI[lang]
        other = [lg for lg in LANGS if lg != lang][0]
        other_href = self.rel(here, self.page_path(part, other, name))
        css = self.rel(here, 'assets/manual.css')
        js = self.rel(here, 'assets/manual.js')
        home = self.rel(here, self.page_path('user', lang, 'index'))
        dev = self.rel(here, self.page_path('dev', lang, 'index'))
        top = self.rel(here, 'index.html')
        part_cls = ' class="current"' if part == 'user' else ''
        dev_cls = ' class="current"' if part == 'dev' else ''
        main_cls = 'content wide' if wide else 'content'
        generated = ui['generated'].format(src=html.escape(src))

        return f'''<!doctype html>
<!-- SPDX-License-Identifier: Apache-2.0 OR MIT -->
<!-- Generated by docs/scripts/build.py from {src}: do not edit -->
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)} · libhdrgrading</title>
<link rel="stylesheet" href="{css}">
<script src="{js}"></script>
</head>
<body>
<a class="skip" href="#main">{ui['skip']}</a>
<header class="top">
<a class="brand" href="{top}">libhdrgrading</a>
<nav class="parts"><a href="{home}"{part_cls}>{ui['manual']}</a><a href="{dev}"{dev_cls}>{ui['dev']}</a></nav>
<div class="tools"><a class="lang" href="{other_href}" hreflang="{other}" lang="{other}">{LANG_NAMES[other]}</a>
<button class="theme" type="button" aria-label="{ui['theme']}" title="{ui['theme']}">◐</button></div>
</header>
<div class="layout{' with-aside' if aside else ''}">
{self.nav(part, lang, here, name)}
<main id="main" class="{main_cls}">
<h1>{html.escape(title) if not title.endswith('.h') else '<code>' + title + '</code>'}</h1>
{body}
<footer class="gen">{generated}</footer>
</main>
{aside}
</div>
</body>
</html>
'''

    def content(self, lang: str, rel: str) -> tuple:
        path = CONTENT / lang / rel
        if not path.exists():
            raise BuildError(f'missing {path.relative_to(ROOT)}')

        return path.read_text(encoding='utf-8'), str(path.relative_to(ROOT))

    def write(self, rel: str, text: str):
        path = self.out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')

    def build(self):
        for lang in LANGS:
            for name, title in USER_PAGES:
                text, src = self.content(lang, f'{name}.html')
                here = self.page_path('user', lang, name)
                body = self.expand(text, 'user', lang, here)
                self.write(here, self.page('user', lang, name, body, title[lang], src))

            for name, title in DEV_PAGES:
                here = self.page_path('dev', lang, name)
                header = name.split('/')[1] + '.h' if name.startswith('api/') and \
                    name != 'api/index' else None
                if header:
                    intro, src = self.content(lang, f'dev/{name}.html')
                    h = next(h for h in self.headers if h.name == header)
                    body, side, _ = apiref.render_header(
                        h, self.linker, lang, self.source_href(here, f'include/hdrgrading/{header}'),
                        self.tr)
                    body = self.expand(intro, 'dev', lang, here) + body
                    src += f', include/hdrgrading/{header}'
                    self.write(here, self.page('dev', lang, name, body, title, src, wide=True,
                                               aside=side))
                    continue
                text, src = self.content(lang, f'dev/{name}.html')
                body = self.expand(text, 'dev', lang, here)
                t = title if isinstance(title, str) else title[lang]
                self.write(here, self.page('dev', lang, name, body, t, src))

            for d in self.diagrams.values():
                self.warnings.extend(d.check(lang))
                self.write(f'{lang}/img/{d.name}.svg', d.render(lang))

        unused = set(self.diagrams) - self.used_figures
        if unused:
            self.warnings.append(f'diagrams not used by any page: {", ".join(sorted(unused))}')

        self.write('index.html', self.landing('index.html', 'user'))
        self.write('dev/index.html', self.landing('dev/index.html', 'dev'))
        self.check_api()
        self.check_links()

    def check_links(self):
        """Every relative link of the pages reaches a file, and its anchor an id there."""
        ids: dict = {}
        pages = sorted(p for p in self.out.rglob('*.html'))
        for page in pages:
            ids[page.resolve()] = set(re.findall(r'\bid="([^"]+)"', page.read_text(encoding='utf-8')))
        for page in pages:
            text = page.read_text(encoding='utf-8')
            for href in re.findall(r'\bhref="([^"]+)"', text):
                href = html.unescape(href)
                if re.match(r'[a-z]+:', href) or href.startswith('//'):
                    continue
                path, _, anchor = href.partition('#')
                # the site's top links what other jobs put beside the docs
                if self.site and page.parent == self.out and path.split('/')[0] in SITE_PARTS:
                    continue
                target = (page.parent / path).resolve() if path else page.resolve()
                try:
                    rel = target.relative_to(self.out.resolve())
                    inside = True
                except ValueError:
                    inside = False
                if inside:
                    if not target.exists() and not (DOCS / rel).exists():
                        raise BuildError(f'{page.relative_to(self.out)}: dead link {href}')
                    if anchor and target.suffix == '.html' and anchor not in ids.get(target, ()):
                        raise BuildError(f'{page.relative_to(self.out)}: no #{anchor} in {rel}')
                elif not self.source_base:
                    # a repository file: the output is built in a temporary directory
                    repo = (self.dest / page.relative_to(self.out)).parent / path
                    if not repo.resolve().exists():
                        raise BuildError(f'{page.relative_to(self.out)}: dead link {href}')

    def landing(self, here: str, part: str) -> str:
        """The language choice (docs/index.html, docs/dev/index.html); on the site, its top."""
        css = self.rel(here, 'assets/manual.css')
        js = self.rel(here, 'assets/manual.js')
        cards = []
        texts = {
            'user': {'en': ('Manual', 'What the library does and how it is built: the layers, the '
                            'pipeline, still images, video sessions, the GPU, plugins, bindings '
                            'and tools, with diagrams.'),
                     'ja': ('マニュアル', 'ライブラリが何をし、どう組み立てられているか: 層・パイプライン・'
                            '静止画・動画のセッション・GPU・プラグイン・バインディング・ツールを図で。')},
            'dev': {'en': ('Developer guide', 'The API reference of the public headers, building, '
                           'the verification tiers and the conventions.'),
                    'ja': ('開発者向けの資料', '公開ヘッダの API リファレンス、ビルド、検証の段階、規約。')},
        }
        for lang in LANGS:
            for p in (['user', 'dev'] if part == 'user' else ['dev']):
                title, text = texts[p][lang]
                href = self.rel(here, self.page_path(p, lang, 'index'))
                cards.append(f'<a class="card" href="{href}" hreflang="{lang}" lang="{lang}">'
                             f'<span class="card-lang">{LANG_NAMES[lang]}</span>'
                             f'<strong>{title}</strong><span>{text}</span></a>')
        heading = 'libhdrgrading' if part == 'user' else 'libhdrgrading · developers / 開発者向け'

        # the published site: what the CI and the WASM build put beside the docs, and the source
        for href, en, ja in (SITE_LINKS if self.site and part == 'user' else ()):
            cards.append(f'<a class="card" href="{href}"><span class="card-lang">Site / サイト</span>'
                         f'<strong>{en[0]} · {ja[0]}</strong><span lang="en">{en[1]}</span>'
                         f'<span lang="ja">{ja[1]}</span></a>')

        return f'''<!doctype html>
<!-- SPDX-License-Identifier: Apache-2.0 OR MIT -->
<!-- Generated by docs/scripts/build.py: do not edit -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>libhdrgrading manual</title>
<link rel="stylesheet" href="{css}">
<script src="{js}"></script>
</head>
<body class="landing">
<main class="landing-main">
<h1>{heading}</h1>
<p class="lead" lang="en">SDR to HDR grading for images and video, in C11.</p>
<p class="lead" lang="ja">SDR の画像と動画を HDR へグレーディングする C11 のライブラリ。</p>
<div class="cards">{"".join(cards)}</div>
<p class="gen">Generated by <code>docs/scripts/build.py</code> · <code>docs/scripts/build.py</code> が作ったページ</p>
</main>
</body>
</html>
'''

    def check_api(self):
        want = apiref.api_functions(ROOT / 'include' / 'hdrgrading')
        have = set()
        for h in self.headers:
            for item in h.items:
                if item.kind == 'function':
                    have.update(item.names)
        if want != have:
            raise BuildError(f'API reference: missing {sorted(want - have)}, '
                             f'extra {sorted(have - want)}')


def generated_files(root: Path) -> set:
    files = set()
    for path in root.rglob('*'):
        if path.is_file() and path.suffix in ('.html', '.svg'):
            rel = path.relative_to(root)
            if rel.parts[0] in ('scripts', 'assets'):
                continue
            files.add(str(rel))

    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true',
                        help='fail when docs/ differs from what would be written')
    parser.add_argument('--strict', action='store_true', help='fail on diagram layout warnings')
    parser.add_argument('--source-base', default='',
                        help='URL of the repository files (default: relative links)')
    parser.add_argument('--out', default='',
                        help='write the whole site (the assets too) into this directory instead '
                             'of updating docs/')
    parser.add_argument('--site', action='store_true',
                        help='with --out: the top links the demo, the coverage and the source')
    args = parser.parse_args()

    if args.out and args.check:
        parser.error('--out and --check go separately')

    if args.site and not args.out:
        parser.error('--site needs --out (the committed docs/ link no site parts)')

    tmp = Path(tempfile.mkdtemp(prefix='hdrg-docs-'))
    try:
        site = Site(tmp, args.source_base, args.site, Path(args.out).resolve() if args.out else DOCS)
        try:
            site.build()
        except (BuildError, apiref.ParseError) as e:
            print(f'error: {e}', file=sys.stderr)
            return 1

        for w in site.warnings:
            print(f'warning: {w}', file=sys.stderr)
        if args.strict and site.warnings:
            return 1

        # the translations: synced to the headers (written by a plain build), then complete
        stale_ja = []
        for header in site.tr.files:
            path, text = site.tr.path(header), site.tr.text(header)
            current = path.read_text(encoding='utf-8') if path.exists() else None
            if current == text:
                continue
            if args.check or args.out:
                stale_ja.append(path)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding='utf-8')
        for path in stale_ja:
            print(f'out of date: {path.relative_to(ROOT)} (run the build)', file=sys.stderr)
        untranslated, problems = site.tr.untranslated(), site.tr.problems()
        for header, of in untranslated:
            print(f'untranslated: docs/scripts/api_ja/{header}.json: {of}', file=sys.stderr)
        for header, of, problem in problems:
            print(f'translation: docs/scripts/api_ja/{header}.json: {of}: {problem}', file=sys.stderr)
        if untranslated or problems:
            print(f'error: {len(untranslated)} comment(s) of the public headers without Japanese, '
                  f'{len(problems)} translation(s) not matching their English '
                  '(docs/scripts/api_ja/README.md)', file=sys.stderr)
            return 1
        if stale_ja:
            return 1

        if args.out:
            out = Path(args.out)
            if out.exists():
                shutil.rmtree(out)
            shutil.copytree(tmp, out)
            shutil.copytree(DOCS / 'assets', out / 'assets')
            print(f'{out}: {len(generated_files(out))} files')
            return 0

        new, old = generated_files(tmp), generated_files(DOCS)
        changed = sorted(f for f in new if not (DOCS / f).exists() or
                         (DOCS / f).read_bytes() != (tmp / f).read_bytes())
        stale = sorted(old - new)

        if args.check:
            for f in changed:
                print(f'out of date: docs/{f}', file=sys.stderr)
            for f in stale:
                print(f'not generated: docs/{f}', file=sys.stderr)
            return 1 if changed or stale else 0

        for f in changed:
            dst = DOCS / f
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(tmp / f, dst)
        for f in stale:
            (DOCS / f).unlink()
        print(f'docs/: {len(new)} files, {len(changed)} written, {len(stale)} removed')

        return 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == '__main__':
    sys.exit(main())
