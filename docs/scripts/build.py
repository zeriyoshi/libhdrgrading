"""Builds the manual (docs/): the diagrams, the pages and the API reference.

    python3 -I docs/scripts/build.py            # write docs/
    python3 -I docs/scripts/build.py --check    # fail when docs/ is not what it would write
    python3 -I docs/scripts/build.py --strict   # fail on layout warnings of the diagrams

The Japanese API reference needs a translation of every comment of the public
headers (docs/scripts/api_ja/<header>.json, see its README.md): the build
brings the files up to date with the headers (a new or changed comment comes in
with "ja": null, an unused entry goes) and fails while one is untranslated or
does not match its English (blocks, list items, identifiers); --check fails
when a file is not up to date.
    python3 -I docs/scripts/build.py --out DIR --site --source-base URL
                                                  # the site to publish (GitHub Pages): the docs
                                                  # in DIR, its top linking the demo (DIR/demo/,
                                                  # scripts/wasm_demo.sh) and the coverage
                                                  # (DIR/coverage/, CI), source links to URL

Sources (edit these): docs/scripts/diagrams.py (the diagrams as data),
docs/scripts/content/<lang>/**.html (the pages' bodies), docs/assets/
(the stylesheet), include/hdrgrading/*.h (the API reference). Everything
else under docs/ is written by this script. Python 3.9+, standard library
only.

Placeholders in the pages' bodies, checked at build time:
    {{fig:NAME}}            a diagram of diagrams.py
    {{src:PATH}}            a link to a file or directory of the repository (must exist)
    {{src:PATH|TEXT}}
    {{api:SYMBOL}}          a link into the API reference (must exist)
    {{api:SYMBOL|TEXT}}
    {{page:NAME|TEXT}}      a page of the same part (the manual, or dev/)
    {{man:NAME|TEXT}}       a page of the manual from dev/
    {{dev:NAME|TEXT}}       a page of dev/ from the manual
"""

