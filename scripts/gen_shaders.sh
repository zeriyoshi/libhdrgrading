#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0 OR MIT
# Generates the GPU shaders from their WGSL (the WGSL is the source, the generated
# shaders are committed) by Tint's CLI of the pinned Dawn tag (scripts/build_dawn.sh --tint), each
# compute entry point of src/<dir>/wgsl/<name>.wgsl, for the plugins' (src/plugins/<name>) and the
# core's (src/core):
#   MSL     src/<dir>/msl/<name>_<entry>.metal  (Metal: src/gpu/metal reads Tint's buffer numbers,
#           which follow the order an entry point uses them, back from the pipeline's reflection
#           by the WGSL names)
#   SPIR-V  src/<dir>/spirv/<name>_<entry>.spv   (Vulkan, and the core's for the apps)
#   HLSL    src/core/hlsl/<name>_<entry>.hlsl    (the core's apply and conversion for the apps)
# The MSL and the HLSL start with the WGSL's leading comment (its SPDX line, copyright and any
# upstream notice of a port).
#
#   scripts/gen_shaders.sh           write the files (and remove those of entry points no longer there)
#   scripts/gen_shaders.sh --check   regenerate into a temporary directory and fail on any difference (CI)
#
# Tint: HDRG_TINT, else $HDRG_DAWN_DIR/bin/tint, build/deps/dawn/bin/tint, build/deps/tint/bin/tint,
# or tint on PATH.
set -euo pipefail

fail() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
check=0
if [[ "${1:-}" == "--check" ]]; then
    check=1
fi

tint="${HDRG_TINT:-}"
if [[ -z "$tint" ]]; then
    for candidate in "${HDRG_DAWN_DIR:+$HDRG_DAWN_DIR/bin/tint}" "$root/build/deps/dawn/bin/tint" \
        "$root/build/deps/tint/bin/tint" "$(command -v tint || true)"; do
        if [[ -n "$candidate" && -x "$candidate" ]]; then
            tint="$candidate"
            break
        fi
    done
fi
[[ -n "$tint" && -x "$tint" ]] || fail "Tint's CLI was not found (scripts/build_dawn.sh --tint, HDRG_TINT)"

status=0

# the HLSL's modules: the core's the apps run (hdrg_shader)
hlsl_modules=" core/apply core/convert "

# one kind of output of one shader directory: src/$1/wgsl into src/$1/$2 (format $3, extension $4)
generate() {
    local dir="$1" kind="$2" format="$3" ext="$4" out wgsl name entries entry file committed keep
    local -a generated=()

    out="$root/src/$dir/$kind"
    if [[ "$check" == 1 ]]; then
        out="$tmp/$dir/$kind"
    fi
    mkdir -p "$out"

    for wgsl in "$root"/src/"$dir"/wgsl/*.wgsl; do
        name="$(basename "$wgsl" .wgsl)"

        if [[ "$kind" == hlsl && "$hlsl_modules" != *" $dir/$name "* ]]; then
            continue
        fi

        # the entry points: a function under @compute (on its line or the next ones up to the fn)
        entries="$(awk '/@compute/ { compute = 1 } compute && match($0, /fn [A-Za-z_][A-Za-z0-9_]*/) {
            print substr($0, RSTART + 3, RLENGTH - 3); compute = 0 }' "$wgsl")"
        [[ -n "$entries" ]] || fail "$wgsl has no compute entry point"

        for entry in $entries; do
            file="${name}_${entry}.${ext}"
            "$tint" --format "$format" --ep "$entry" -o "$out/$file.tint" "$wgsl"

            if [[ "$kind" == spirv ]]; then
                mv "$out/$file.tint" "$out/$file"
            else
                {
                    awk '/^\/\// { print; next } { exit }' "$wgsl"
                    printf '//\n'
                    printf '// Generated by scripts/gen_shaders.sh from src/%s/wgsl/%s.wgsl (entry point %s)\n' \
                        "$dir" "$name" "$entry"
                    printf "// with Tint's CLI: do not edit.\n"
                    cat "$out/$file.tint"
                } > "$out/$file"
                rm -f "$out/$file.tint"
            fi

            generated+=("$file")
        done
    done

    if [[ "$check" == 1 ]]; then
        for file in "${generated[@]}"; do
            if ! cmp -s "$out/$file" "$root/src/$dir/$kind/$file"; then
                printf 'src/%s/%s/%s differs from its WGSL (run scripts/gen_shaders.sh)\n' "$dir" "$kind" \
                    "$file" >&2

                if [[ "$kind" != spirv ]]; then
                    diff -u "$root/src/$dir/$kind/$file" "$out/$file" >&2 || true
                fi

                status=1
            fi
        done
        for committed in "$root"/src/"$dir"/"$kind"/*."$ext"; do
            [[ -e "$committed" ]] || continue
            if [[ ! -e "$out/$(basename "$committed")" ]]; then
                printf 'src/%s/%s/%s has no entry point in the WGSL\n' "$dir" "$kind" \
                    "$(basename "$committed")" >&2
                status=1
            fi
        done

        return
    fi

    for committed in "$out"/*."$ext"; do
        [[ -e "$committed" ]] || continue
        keep=0
        for file in "${generated[@]}"; do
            if [[ "$(basename "$committed")" == "$file" ]]; then
                keep=1
            fi
        done
        if [[ "$keep" == 0 ]]; then
            rm -f "$committed"
        fi
    done
}

tmp=""
if [[ "$check" == 1 ]]; then
    tmp="$(mktemp -d)"
    trap 'rm -rf "$tmp"' EXIT
fi

dirs=(core)
for plugin in "$root"/src/plugins/*/wgsl; do
    dirs+=("plugins/$(basename "$(dirname "$plugin")")")
done

for dir in "${dirs[@]}"; do
    generate "$dir" msl msl metal
    generate "$dir" spirv spirv spv
done

generate core hlsl hlsl hlsl

exit "$status"
