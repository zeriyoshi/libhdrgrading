"""Trains the light predictor and writes its weights (needs numpy).

    python3 -I scripts/predictor/train.py ROWS DATA_DIR src/plugins/predict/predict_weights.c

ROWS is hdrg-predictor-data's output over DATA_DIR's PNGs (make_data.py). Each judged light (a
boost above 0) is labelled by its HDR truth: the brightest exposed luminance in its core's box,
its chance of a light min(max(log2(that) / 2, 0), 1) (white at 1: two stops above it a light for
sure, at or under it none). A 10-16-8-1 perceptron (ReLU, the output clamped to 0..1) learns it
(Adam, mean squared error, weight decay, the weights kept within int8 of 1/64), then is quantized as
src/plugins/predict computes it (features of 1/2048, weights of 1/64) and checked in that integer
arithmetic. The light version: its accuracy is to be refined.
"""

import os
import sys

import numpy as np

ONE = 2048
WEIGHT = 64
LIMIT = 8 * ONE
SIZES = (10, 16, 8, 1)


def read_rows(path, data_dir):
    features, labels = [], []
    truth = None
    images = 0
    for line in open(path, encoding="utf-8"):
        fields = line.split()
        if line.startswith("#"):
            stem = os.path.splitext(os.path.basename(fields[1]))[0]
            truth = np.load(os.path.join(data_dir, stem + ".npy"))
            images += 1
            continue
        x0, y0, x1, y1 = (int(v) for v in fields[:4])
        f = [float(v) for v in fields[4:]]
        if f[7] <= 0.0:
            continue
        brightest = float(truth[y0:y1, x0:x1].max())
        labels.append(min(max(np.log2(max(brightest, 1e-6)) / 2.0, 0.0), 1.0))
        features.append(f)
    return np.array(features, dtype=np.float64), np.array(labels, dtype=np.float64), images


def forward(params, x):
    h = x
    acts = [h]
    for i in range(3):
        h = h @ params[2 * i].T + params[2 * i + 1]
        if i < 2:
            h = np.maximum(h, 0.0)
        acts.append(h)
    return acts


def train(x, y, epochs=4000, rate=3e-3, decay=1e-4, seed=7):
    rng = np.random.default_rng(seed)
    params = []
    for fan_in, fan_out in zip(SIZES[:-1], SIZES[1:]):
        params.append(rng.normal(0.0, np.sqrt(2.0 / fan_in), (fan_out, fan_in)))
        params.append(np.zeros(fan_out))
    params[-1][:] = 0.5
    m = [np.zeros_like(p) for p in params]
    v = [np.zeros_like(p) for p in params]
    bound = 127.0 / WEIGHT
    for step in range(1, epochs + 1):
        acts = forward(params, x)
        out = acts[-1][:, 0]
        clamped = np.clip(out, 0.0, 1.0)
        grad = (2.0 * (clamped - y) * ((out > 0.0) & (out < 1.0)))[:, None] / len(y)
        grads = [None] * 6
        for i in (2, 1, 0):
            grads[2 * i] = grad.T @ acts[i] + decay * params[2 * i]
            grads[2 * i + 1] = grad.sum(axis=0)
            if i > 0:
                grad = (grad @ params[2 * i]) * (acts[i] > 0.0)
        for i, g in enumerate(grads):
            m[i] = 0.9 * m[i] + 0.1 * g
            v[i] = 0.999 * v[i] + 0.001 * g * g
            params[i] -= rate * (m[i] / (1 - 0.9 ** step)) / (np.sqrt(v[i] / (1 - 0.999 ** step)) + 1e-8)
            if i % 2 == 0:
                np.clip(params[i], -bound, bound, out=params[i])
    return params


def quantize(params):
    weights = [np.clip(np.round(params[2 * i] * WEIGHT), -127, 127).astype(np.int64) for i in range(3)]
    biases = [np.round(params[2 * i + 1] * ONE * WEIGHT).astype(np.int64) for i in range(3)]
    return weights, biases


def fixed_chance(weights, biases, x):
    """src/plugins/predict/predict.c's integer arithmetic (truncating divisions of non-negative sums)."""
    q = np.floor(np.clip(x, -8.0, 8.0) * ONE + LIMIT + 0.5).astype(np.int64) - LIMIT
    h = q
    for i in range(2):
        acc = h @ weights[i].T + biases[i]
        h = np.where(acc > 0, np.minimum(acc // WEIGHT, LIMIT), 0)
    acc = h @ weights[2].T + biases[2]
    out = np.where(acc >= 0, acc // WEIGHT, -((-acc) // WEIGHT))
    return np.clip(out[:, 0], 0, ONE)


def c_array(values):
    return "{" + ", ".join(str(int(v)) for v in values) + "}"


def write_c(path, weights, biases, lights, images, mae):
    w1 = ",\n    ".join(c_array(row) for row in weights[0])
    w2 = ",\n    ".join(c_array(row) for row in weights[1])
    text = f"""/*
 * SPDX-License-Identifier: Apache-2.0 OR MIT
 * Copyright (c) 2026 Go Kudo <zeriyoshi@gmail.com>
 */

/*
 * generated by scripts/predictor/train.py: {lights} judged lights of {images} SDR stills made from
 * Poly Haven HDRIs (CC0), the integer chance's mean absolute error {mae:.3f}
 */

#include "parts.h"

const int8_t hdrg_predict_w1[HDRG_PREDICT_HIDDEN1][HDRG_LIGHT_FEATURES] = {{
    {w1}}};
const int32_t hdrg_predict_b1[HDRG_PREDICT_HIDDEN1] = {c_array(biases[0])};
const int8_t hdrg_predict_w2[HDRG_PREDICT_HIDDEN2][HDRG_PREDICT_HIDDEN1] = {{
    {w2}}};
const int32_t hdrg_predict_b2[HDRG_PREDICT_HIDDEN2] = {c_array(biases[1])};
const int8_t hdrg_predict_w3[HDRG_PREDICT_HIDDEN2] = {c_array(weights[2][0])};
const int32_t hdrg_predict_b3 = {int(biases[2][0])};
"""
    open(path, "w", encoding="utf-8").write(text)


def main(argv):
    if len(argv) < 4:
        print(__doc__, file=sys.stderr)
        return 2
    x, y, images = read_rows(argv[1], argv[2])
    if len(y) < 20:
        print(f"too few lights: {len(y)}", file=sys.stderr)
        return 1
    order = np.random.default_rng(1).permutation(len(y))
    held = order[: len(y) // 5]
    fit = order[len(y) // 5:]
    params = train(x[fit], y[fit])
    weights, biases = quantize(params)
    chance = fixed_chance(weights, biases, x) / ONE
    base = float(np.mean(np.abs(y[held] - y[fit].mean())))
    print(f"{len(y)} lights of {images} stills (labels mean {y.mean():.3f}); held-out MAE "
          f"{np.mean(np.abs(chance[held] - y[held])):.3f} (the mean alone {base:.3f}), "
          f"fitted {np.mean(np.abs(chance[fit] - y[fit])):.3f}")
    params = train(x, y)
    weights, biases = quantize(params)
    mae = float(np.mean(np.abs(fixed_chance(weights, biases, x) / ONE - y)))
    write_c(argv[3], weights, biases, len(y), images, mae)
    print(f"all {len(y)}: MAE {mae:.3f} -> {argv[3]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
